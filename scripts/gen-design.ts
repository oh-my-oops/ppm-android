// Generates the design module's data from the web app's own sources, so the Android app cannot
// drift from the browser: the six built-in themes (src/web/theme/builtin), the product icons
// (src/web/lib/icons.generated.tsx — Fluent System Icons, and the few it keeps on lucide) and the
// provider logos (src/web/lib/provider-logos.tsx). Re-run after any of those change:
//
//   bun android/scripts/gen-design.ts
import { resolve } from "node:path";
import { BUILTIN_ORDER, BUILTIN_THEMES } from "../../src/web/theme/builtin";
import type { PpmTheme, PpmThemeTokens } from "../../src/web/theme/types";

const repo = resolve(import.meta.dir, "../..");
const outDir = resolve(repo, "android/ui/design/src/main/kotlin/com/hienlh/ppm/design");
const HEADER = (source: string) =>
  `// GENERATED by \`bun android/scripts/gen-design.ts\` from ${source} — do not edit.\npackage com.hienlh.ppm.design\n`;

/** A Kotlin string literal. */
const kt = (s: string) =>
  `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$").replace(/\n/g, "\\n")}"`;

// ── Colours ────────────────────────────────────────────────────────────────────

/** Channels 0–255 and alpha 0–1, exactly as written. */
type RGBA = [number, number, number, number];

function parseColor(value: string): RGBA {
  const v = value.trim();
  let m = /^#([0-9a-f]{3}|[0-9a-f]{6}|[0-9a-f]{8})$/i.exec(v);
  if (m) {
    let hex = m[1]!;
    if (hex.length === 3) hex = [...hex].map((c) => c + c).join("");
    const n = (i: number) => parseInt(hex.slice(i, i + 2), 16);
    return [n(0), n(2), n(4), hex.length === 8 ? n(6) / 255 : 1];
  }
  m = /^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)$/i.exec(v);
  if (m) return [Number(m[1]), Number(m[2]), Number(m[3]), m[4] === undefined ? 1 : Number(m[4])];
  throw new Error(`Unsupported colour: ${value}`);
}

const num = (n: number) => {
  const s = n.toFixed(4).replace(/0+$/, "").replace(/\.$/, "");
  return s === "-0" ? "0.0" : s.includes(".") ? s : `${s}.0`;
};
// Channels as `n / 255.0` so they equal what `Rgba.hex` computes at run time, bit for bit.
const color = (value: string) => {
  const [r, g, b, a] = parseColor(value);
  return `Rgba(${r} / 255.0, ${g} / 255.0, ${b} / 255.0, ${num(a)})`;
};

/** `radial-gradient(120% 120% at 0% 0%, #a 0%, #b 55%, #c 100%)` → stops; a plain colour → Solid. */
function background(value: string): string {
  const m = /^radial-gradient\(\s*([\d.]+)%\s+([\d.]+)%\s+at\s+([\d.]+)%\s+([\d.]+)%\s*,(.*)\)$/i.exec(value.trim());
  if (!m) return `ThemeBackground.Solid(${color(value)})`;
  if (m[1] !== m[2]) throw new Error(`Unsupported gradient size: ${value}`);
  const stops = m[5]!.split(/,(?![^(]*\))/).map((s) => {
    const sm = /^\s*(.+?)\s+([\d.]+)%\s*$/.exec(s);
    if (!sm) throw new Error(`Unsupported gradient stop: ${s}`);
    return `GradientStop(${color(sm[1]!)}, ${num(Number(sm[2]) / 100)})`;
  });
  return `ThemeBackground.Radial(radius = ${num(Number(m[1]) / 100)}, centerX = ${num(Number(m[3]) / 100)}, centerY = ${num(Number(m[4]) / 100)}, stops = listOf(${stops.join(", ")}))`;
}

/** `0 30px 70px -24px rgba(0,0,0,0.65)` → x, y, blur, spread, colour. */
function shadow(value: string): string {
  const m = /^\s*(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+([\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(.+)$/.exec(value);
  if (!m) throw new Error(`Unsupported shadow: ${value}`);
  return `ThemeShadow(x = ${num(Number(m[1]))}, y = ${num(Number(m[2]))}, blur = ${num(Number(m[3]))}, spread = ${num(Number(m[4]))}, color = ${color(m[5]!)})`;
}

const px = (value: string) => {
  const m = /^([\d.]+)px$/.exec(value.trim());
  if (!m) throw new Error(`Unsupported length: ${value}`);
  return num(Number(m[1]));
};

/** One token as the Kotlin `ThemeTokens` field it fills; `blur` has none (no glass themes here). */
function token(key: string, value: string): [string, string] | null {
  switch (key) {
    case "bg":
      return ["background", background(value)];
    case "blur":
      return null;
    case "shadowPanel":
    case "shadowFloat":
      return [key, shadow(value)];
    case "rad":
    case "radSm":
      return [key, px(value)];
    default:
      return [key, color(value)];
  }
}

const fields = (tokens: Partial<PpmThemeTokens>, indent: string) =>
  Object.entries(tokens)
    .map(([k, v]) => token(k, String(v)))
    .filter((f): f is [string, string] => f !== null)
    .map(([k, v]) => `${indent}${k} = ${v},`)
    .join("\n");

const camel = (id: string) => id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

const themes = BUILTIN_ORDER.map((id) => BUILTIN_THEMES[id]!);
const theme = (t: PpmTheme) => {
  const mobile = t.mobileOverrides ?? {};
  const mobileTokens = Object.keys(mobile).length === 0 ? "tokens" : `tokens.copy(\n${fields(mobile, "                ")}\n            )`;
  return `    val ${camel(t.id)}: PpmTheme = run {
        val tokens = ThemeTokens(
${fields(t.tokens, "            ")}
        )
        PpmTheme(
            id = ${kt(t.id)},
            name = ${kt(t.name)},
            style = ${kt(t.style)},
            isDark = ${t.mode === "dark"},
            swatch = listOf(${t.swatch.map(color).join(", ")}),
            shikiTheme = ${kt(typeof t.syntax?.shikiTheme === "string" ? t.syntax.shikiTheme : "github-dark-dimmed")},
            tokens = tokens,
            mobileTokens = ${mobileTokens},
        )
    }`;
};
const themeKotlin = `${HEADER("src/web/theme/builtin")}
/** The web's built-in themes. */
object BuiltInThemes {
${themes.map(theme).join("\n\n")}

    /** The web's BUILTIN_ORDER. */
    val all: List<PpmTheme> = listOf(${themes.map((t) => camel(t.id)).join(", ")})
}
`;

// ── Product icons ──────────────────────────────────────────────────────────────

const iconSource = await Bun.file(resolve(repo, "src/web/lib/icons.generated.tsx")).text();
const glyphs = new Map<string, string[]>();
for (const m of iconSource.matchAll(/^\s+"([a-z0-9-]+)": (\[.*\]),$/gm)) glyphs.set(m[1]!, JSON.parse(m[2]!));
const exportsByGlyph = new Map<string, string[]>();
for (const m of iconSource.matchAll(/^export const (\w+) = fluentIcon\("\w+", D\["([a-z0-9-]+)"\]!\);$/gm)) {
  const list = exportsByGlyph.get(m[2]!) ?? [];
  list.push(m[1]!);
  exportsByGlyph.set(m[2]!, list);
}
if (glyphs.size === 0 || exportsByGlyph.size === 0) throw new Error("icons.generated.tsx changed shape");
const allExports = [...exportsByGlyph.values()].flat().sort();
const iconKotlin = `${HEADER("src/web/lib/icons.generated.tsx")}
/**
 * The web's product icons by their export name (\`MessageSquare\` → \`ProductIcon.MessageSquare\`):
 * Fluent System Icons, 20px Regular, MIT (microsoft/fluentui-system-icons). Filled outlines in a
 * 20×20 box. The few the web keeps on lucide are not here.
 */
enum class ProductIcon {
${allExports.map((name) => `    ${name},`).join("\n")}
    ;

    /** SVG path data in a 20×20 view box, filled with the non-zero rule. */
    val pathData: List<String>
        get() = when (this) {
${[...exportsByGlyph.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([glyph, names]) => {
    const paths = glyphs.get(glyph);
    if (!paths) throw new Error(`No path data for ${glyph}`);
    return `            // ${glyph}\n            ${names.join(", ")} -> listOf(${paths.map(kt).join(", ")})`;
  })
  .join("\n")}
        }
}
`;

// ── Lucide icons ───────────────────────────────────────────────────────────────

const lucideNames: string[] = JSON.parse(/^export const LUCIDE_NAMES: readonly string\[\] = (\[.*\]);$/m.exec(iconSource)?.[1] ?? "[]");
if (lucideNames.length === 0) throw new Error("icons.generated.tsx no longer lists LUCIDE_NAMES");
const lucideDir = resolve(repo, "node_modules/lucide-react/dist/esm/icons");
const lucideVersion: string = (await Bun.file(resolve(repo, "node_modules/lucide-react/package.json")).json()).version;

type LucideNode = [string, Record<string, string>][];

/** The icon's node list; a name lucide keeps as an alias re-exports the icon it now is. */
async function lucideNode(name: string): Promise<LucideNode> {
  let file = resolve(lucideDir, `${name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([a-zA-Z])([0-9])/g, "$1-$2").toLowerCase()}.js`);
  for (;;) {
    const alias = /^export \{ default \} from '\.\/([a-z0-9-]+\.js)';$/m.exec(await Bun.file(file).text());
    if (!alias) break;
    file = resolve(lucideDir, alias[1]!);
  }
  const node = (await import(file)).__iconNode as LucideNode | undefined;
  if (!node) throw new Error(`No icon node in ${file}`);
  return node;
}

/** One SVG element of a lucide icon as path data, in its 24×24 box. */
function elementPath([tag, a]: [string, Record<string, string>]): string {
  const n = (k: string) => Number(a[k] ?? 0);
  const points = () => (a.points ?? "").trim().split(/[\s,]+/).map(Number);
  switch (tag) {
    case "path":
      return a.d!;
    case "line":
      return `M${n("x1")} ${n("y1")}L${n("x2")} ${n("y2")}`;
    case "circle":
    case "ellipse": {
      const rx = tag === "circle" ? n("r") : n("rx");
      const ry = tag === "circle" ? n("r") : n("ry");
      return `M${n("cx") - rx} ${n("cy")}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0z`;
    }
    case "rect": {
      const [x, y, w, h] = [n("x"), n("y"), n("width"), n("height")];
      // SVG: a missing radius takes the other one, and neither exceeds half the side.
      const rx = Math.min(a.rx !== undefined ? n("rx") : n("ry"), w / 2);
      const ry = Math.min(a.ry !== undefined ? n("ry") : n("rx"), h / 2);
      if (rx === 0 || ry === 0) return `M${x} ${y}h${w}v${h}h${-w}z`;
      return `M${x + rx} ${y}h${w - 2 * rx}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${h - 2 * ry}a${rx} ${ry} 0 0 1 ${-rx} ${ry}` +
        `h${-(w - 2 * rx)}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}v${-(h - 2 * ry)}a${rx} ${ry} 0 0 1 ${rx} ${-ry}z`;
    }
    case "polyline":
    case "polygon": {
      const p = points();
      const d = p.reduce((acc, v, i) => acc + (i % 2 === 0 ? `${i === 0 ? "M" : "L"}${v}` : ` ${v}`), "");
      return tag === "polygon" ? `${d}z` : d;
    }
    default:
      throw new Error(`Unsupported lucide element: ${tag}`);
  }
}

const lucideIcons = await Promise.all(lucideNames.map(async (name) => ({ name, paths: (await lucideNode(name)).map(elementPath) })));
const lucideKotlin = `${HEADER(`src/web/lib/icons.generated.tsx (LUCIDE_NAMES) and lucide-react ${lucideVersion}`)}
/**
 * The few icons the web keeps on lucide (lucide-react ${lucideVersion}, ISC), by their export name:
 * outlines in a 24×24 box, stroked 2 wide with round caps and joins.
 */
enum class LucideIcon {
${lucideIcons.map(({ name }) => `    ${name},`).join("\n")}
    ;

    /** SVG path data in a 24×24 view box, stroked rather than filled. */
    val pathData: List<String>
        get() = when (this) {
${lucideIcons.map(({ name, paths }) => `            ${name} -> listOf(${paths.map(kt).join(", ")})`).join("\n")}
        }
}
`;

// ── Provider logos ─────────────────────────────────────────────────────────────

const logoSource = await Bun.file(resolve(repo, "src/web/lib/provider-logos.tsx")).text();
const logoPaths: Record<string, string> = {};
for (const name of ["Claude", "Codex", "Cursor", "Gemini"]) {
  const body = new RegExp(`export function ${name}Logo[\\s\\S]*?\\n}\\n`).exec(logoSource)?.[0];
  const d = body && /\bd="([^"]+)"/.exec(body)?.[1];
  if (!d) throw new Error(`No path for ${name}Logo`);
  logoPaths[name.toLowerCase()] = d;
}
const logoKotlin = `${HEADER("src/web/lib/provider-logos.tsx")}
/** Path data of the AI providers' logos (LobeHub icons, MIT), in a 24×24 view box. */
internal object ProviderLogoPaths {
${Object.entries(logoPaths)
  .map(([k, d]) => `    const val ${k.toUpperCase()} = ${kt(d)}`)
  .join("\n")}
}
`;

await Bun.write(resolve(outDir, "Themes.generated.kt"), themeKotlin);
await Bun.write(resolve(outDir, "ProductIcons.generated.kt"), iconKotlin);
await Bun.write(resolve(outDir, "LucideIcons.generated.kt"), lucideKotlin);
await Bun.write(resolve(outDir, "ProviderLogoPaths.generated.kt"), logoKotlin);
console.log(`themes ${themes.length}, icons ${allExports.length} (${exportsByGlyph.size} glyphs), lucide ${lucideIcons.length}, logos ${Object.keys(logoPaths).length}`);
