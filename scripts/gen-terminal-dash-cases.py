#!/usr/bin/env python3
"""Chrome's own dashed underlines, measured: the oracle for `dashedLine` in TerminalLinkInput.kt.

    python3 -I android/scripts/gen-terminal-dash-cases.py > android/ui/terminal-engine/src/test/resources/terminal-dash-cases.tsv

xterm draws an OSC 8 link with `text-decoration: dashed underline` (`.xterm-underline-5`), so what the app has to match is
how Chrome lays out the dashes. This renders one underlined span per (thickness, length) in headless Chrome at a device scale
factor of 1 (so a CSS pixel is a device pixel, which is where Blink works) and reads the ink of the underline's row, a
coverage per pixel column, off the screenshot. Rows: `case<TAB>thickness<TAB>length<TAB>coverage,coverage,...` with one
coverage (0 to 1) for each pixel from the span's left edge to two past its right one.

Needs Google Chrome (CHROME_BIN, else google-chrome-stable on PATH) and Pillow. Nothing else is touched: the browser runs with
a fresh profile in a temporary directory.
"""

import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

THICKNESS = [1, 2, 3, 4, 5]
LENGTHS = list(range(1, 49))
LEFT = 10  # px from the page's left edge to the span
BAND = 30  # px per row of the page


def page():
    rows = []
    for t in THICKNESS:
        for length in LENGTHS:
            rows.append((t, length))
    html = [
        "<!doctype html><meta charset=utf-8><style>",
        "body{margin:0;background:#fff}",
        f".r{{height:{BAND}px;position:relative}}",
        f".s{{position:absolute;left:{LEFT}px;top:4px;font:20px/20px monospace;color:#000;text-decoration:underline dashed #000;white-space:pre}}",
        "</style><body>",
    ]
    for i, (t, length) in enumerate(rows):
        html.append(f'<div class="r"><span class="s" style="text-decoration-thickness:{t}px" data-length="{length}">&nbsp;</span></div>')
    html.append(
        "<script>document.querySelectorAll('.s').forEach(function(s){"
        "var advance=s.getBoundingClientRect().width;"
        "s.style.letterSpacing=(parseFloat(s.dataset.length)-advance)+'px';});</script>"
    )
    return rows, "\n".join(html)


def chrome():
    return os.environ.get("CHROME_BIN") or shutil.which("google-chrome-stable") or shutil.which("google-chrome") or shutil.which("chromium")


def main():
    binary = chrome()
    if not binary:
        sys.exit("No Chrome: set CHROME_BIN")
    rows, html = page()
    with tempfile.TemporaryDirectory(prefix="ppm-dash-") as scratch:
        scratch = Path(scratch)
        (scratch / "dash.html").write_text(html)
        height = BAND * len(rows) + 20
        subprocess.run(
            [binary, "--headless=new", "--no-sandbox", "--disable-gpu", f"--user-data-dir={scratch / 'profile'}", "--force-device-scale-factor=1",
             f"--window-size=400,{height}", f"--screenshot={scratch / 'dash.png'}", (scratch / "dash.html").as_uri()],
            check=True, capture_output=True,
        )
        image = Image.open(scratch / "dash.png").convert("L")
    print("# Chrome's dashed underlines: thickness and length in device pixels, then the ink in each pixel column (generated by android/scripts/gen-terminal-dash-cases.py)")
    for i, (t, length) in enumerate(rows):
        top, bottom = i * BAND, (i + 1) * BAND
        best = None
        for y in range(top, bottom):
            ink = [(255 - image.getpixel((x, y))) / 255.0 for x in range(LEFT, LEFT + length + 2)]
            if best is None or sum(ink) > sum(best):
                best = ink
        assert sum(best) > 0, f"nothing drawn for thickness {t} length {length}"
        print("case\t%d\t%d\t%s" % (t, length, ",".join("%.2f" % c for c in best)))


if __name__ == "__main__":
    main()
