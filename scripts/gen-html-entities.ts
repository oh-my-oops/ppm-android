// Writes every named character reference HTML knows (character-entities, the table micromark
// and parse5 decode with) and the ones HTML also reads without a `;` (character-entities-legacy)
// into ui/chat, for the app's markdown and HTML to decode `&rarr;` and `&copy` as the web does.
//
//   bun android/scripts/gen-html-entities.ts
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { characterEntities } from "character-entities";
import { characterEntitiesLegacy } from "character-entities-legacy";

const out = resolve(import.meta.dir, "../ui/chat/src/main/kotlin/com/hienlh/ppm/chat/HtmlEntities.generated.kt");

// A Kotlin string literal: control characters, quotes, `$` and backslashes escaped.
const literal = (text: string) =>
  [...text].map((ch) => {
    const code = ch.codePointAt(0)!;
    if (ch === "\\" || ch === '"' || ch === "$") return `\\${ch}`;
    if (code < 0x20 || code === 0x7f) return `\\u${code.toString(16).padStart(4, "0")}`;
    return ch;
  }).join("");

const names = Object.keys(characterEntities).sort();
// Name, U+0001, value, U+0002 — neither appears in any name or value.
const table = names.map((name) => `${name}\u0001${characterEntities[name]}\u0002`).join("");
const chunks: string[] = [];
for (let at = 0; at < table.length; at += 12000) chunks.push(table.slice(at, at + 12000));

const kotlin = `// GENERATED by \`bun android/scripts/gen-html-entities.ts\` from character-entities and character-entities-legacy — do not edit.
package com.hienlh.ppm.chat

/** HTML's named character references, as the web's parsers decode them. */
internal object HtmlEntities {
    /** Every name (without its \`;\`) and what it stands for: ${names.length} of them. */
    val named: Map<String, String> by lazy {
        val map = HashMap<String, String>(${Math.ceil(names.length / 0.75)})
        for (entry in (${chunks.map((chunk) => `"${literal(chunk)}"`).join(" +\n            ")}).split('\\u0002')) {
            val split = entry.indexOf('\\u0001')
            if (split > 0) map[entry.substring(0, split)] = entry.substring(split + 1)
        }
        map
    }

    /** The names HTML also reads with no \`;\` after them (\`&copy\`, \`&amp\`), in text and, unless a name or \`=\` follows, in attributes. */
    val legacy: Set<String> = setOf(
${[...characterEntitiesLegacy].sort().map((name) => `        "${name}",`).join("\n")}
    )

    /** The longest name in [named], for a scan that reads no further. */
    const val LONGEST = ${Math.max(...names.map((name) => name.length))}
}
`;
writeFileSync(out, kotlin);
console.log(`${names.length} names, ${characterEntitiesLegacy.length} legacy -> ${out}`);
