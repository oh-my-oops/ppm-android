const chrome = process.env.CHROME_BIN ?? ["google-chrome-stable", "google-chrome", "chromium", "chromium-browser"].find((name) => Bun.which(name));
if (!chrome) throw new Error("Needs a Chrome on the PATH or in CHROME_BIN: its URL parser is the web client's");
/**
 * What Chrome makes of [texts] (whether the addon's own `isUrl` accepts each, and whether OscLinkProvider's rule shows it as a link)
 * and of [hostTexts] (the `hostname` `new URL` serializes for each, null where it throws). The answers come back as base64 JSON: a
 * hostname can hold `&`, which `--dump-dom` would write as an entity.
 */
function inChrome(texts: string[], hostTexts: string[]): { urls: [boolean, boolean][]; hosts: (string | null)[] } {
  const dir = mkdtempSync(join(tmpdir(), "chrome-urls-"));
  try {
    const page = `<!doctype html><meta charset="utf-8"><pre id="out"></pre><script>
${new Bun.Transpiler({ loader: "ts" }).transformSync(isUrlSource!)}
const texts = ${JSON.stringify(texts)};
const hostTexts = ${JSON.stringify(hostTexts)};
const shown = (uri) => { try { return ["http:", "https:"].includes(new URL(uri).protocol); } catch { return false; } };
const hostname = (host) => { try { return new URL("http://" + host + "/").hostname; } catch { return null; } };
const answer = { urls: texts.map((t) => [isUrl(t) ? 1 : 0, shown(t) ? 1 : 0]), hosts: hostTexts.map(hostname) };
document.getElementById("out").textContent = btoa(unescape(encodeURIComponent(JSON.stringify(answer))));
</script>`;
    writeFileSync(join(dir, "urls.html"), page);
    const run = Bun.spawnSync([chrome!, "--headless=new", "--disable-gpu", "--no-first-run", `--user-data-dir=${join(dir, "profile")}`, "--dump-dom", `file://${join(dir, "urls.html")}`], { stdout: "pipe", stderr: "pipe", timeout: 120_000 });
    const encoded = run.stdout.toString().match(/<pre id="out">(.*?)<\/pre>/s)?.[1];
    if (!encoded) throw new Error(`Chrome gave no answer: ${run.stderr.toString().slice(0, 300)}`);
    const answer = JSON.parse(Buffer.from(encoded, "base64").toString("utf8")) as { urls: number[][]; hosts: (string | null)[] };
    return { urls: answer.urls.map(([url, osc]) => [url === 1, osc === 1]), hosts: answer.hosts };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const bufferLines: string[] = [];
const linkTexts = new Set<string>();
const term = (s: Scenario) => new Terminal({ cols: s.cols, rows: s.rows, scrollback: s.scrollback ?? 1000, allowProposedApi: true });
for (const scenario of scenarios) {
  const t = term(scenario);
  await new Promise<void>((done) => t.write(scenario.output, done));
  const buffer = t.buffer.active;
  const cell = buffer.getNullCell();
  bufferLines.push(`#buffer\t${scenario.name}\t${scenario.cols}\t${buffer.length}`);
  for (let y = 0; y < buffer.length; y++) {
    const row = buffer.getLine(y)!;
    let cells = "";
    for (let x = 0; x < row.length; x++) {
      row.getCell(x, cell);
      cells += cell.getWidth() === 0 ? CONTINUATION : cell.getChars() === "" ? EMPTY : cell.getChars();
    }
    bufferLines.push(`row\t${row.isWrapped ? 1 : 0}\t${esc(cells)}`);
  }
  for (let y = 1; y <= buffer.length; y++) {
    for (const link of LinkComputer.computeLink(y, regex, t as never, () => {})) {
      const { start, end } = link.range;
      linkTexts.add(link.text);
      bufferLines.push(`link\t${y}\t${start.x}\t${start.y}\t${end.x}\t${end.y}\t${link.text.length}\t${fnv(link.text)}\t${esc(link.text.slice(0, 60))}`);
    }
  }
  t.dispose();
}

