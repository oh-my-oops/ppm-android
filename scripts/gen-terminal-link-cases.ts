// A buffer's links are decided by bun's `isUrl`, inside the addon's own `LinkComputer`. Chrome has to give the same answer for every
// match of the regex in those buffers (what a link is, and what a row's text only looks like one) or they would rest on bun's parser.
const matches = [...new Set([...linkTexts, ...scenarios.flatMap((s) => s.output.split(eol).flatMap((line) => [...line.matchAll(new RegExp(regex.source, "g"))].map((m) => m[0])))])];
const sortedHosts = [...hostTexts].sort();
const { urls: answers, hosts: hostAnswers } = inChrome([...sorted, ...matches], sortedHosts);
