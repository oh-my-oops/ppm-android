// Writes the web's allow-list for HTML inside markdown (`markdownSanitizeSchema`, rehype-sanitize's
// GitHub schema plus PPM's changes) into ui/chat, with how hastscript names and types each attribute
// the schema can keep (property-information), so the app keeps exactly what the web keeps.
// Re-run after the schema changes:
//
//   PPM_HOME=$(mktemp -d) bun android/scripts/gen-html-schema.ts
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { find, html, svg } from "property-information";
import { markdownSanitizeSchema as schema } from "../../src/web/components/shared/markdown-sanitize";

const out = resolve(import.meta.dir, "../ui/chat/src/main/kotlin/com/hienlh/ppm/chat/HtmlSchema.generated.kt");

const str = (text: string) => JSON.stringify(text).replace(/\$/g, "\\$");
const list = (items: string[]) => items.map(str).join(", ");
const allowed = (value: unknown): string => {
  if (value instanceof RegExp) {
    // Java's `.` also refuses U+0085, JavaScript's does not; spell JavaScript's out. Anything
    // fancier than literals, `^`, `$` and `.` would need translating too, so it is refused.
    if (value.flags || !/^[\^]?[\w-]*\.?[$]?$/.test(value.source)) throw new Error(`regex ${value} is not handled`);
    return `Regex(${str(value.source.replace(".", "[^\\n\\r\\u2028\\u2029]"))})`;
  }
  if (typeof value === "string") return str(value);
  if (typeof value === "boolean") return String(value);
  throw new Error(`allowed value ${String(value)} is not handled`);
};

const attributes = Object.entries(schema.attributes ?? {}).map(([tag, defs]) => {
  const entries = (defs as (string | [string, ...unknown[]])[]).map((def) =>
    typeof def === "string" ? `HtmlAllowed(${str(def)})` : `HtmlAllowed(${str(def[0])}, listOf(${def.slice(1).map(allowed).join(", ")}))`);
  return `        ${str(tag)} to listOf(\n            ${entries.join(",\n            ")},\n        ),`;
});

const required = Object.entries(schema.required ?? {}).map(([tag, props]) =>
  `        ${str(tag)} to listOf(${Object.entries(props as Record<string, unknown>).map(([key, value]) =>
    `${str(key)} to ${typeof value === "boolean" ? (value ? "HtmlValue.True" : "error(\"false\")") : `HtmlValue.Text(${str(String(value))})`}`).join(", ")}),`);

// Every property the schema names, under each spelling of it property-information resolves to it:
// the attribute (`class`, `aria-describedby`) and the lower-cased property (`classname`).
const flags = ["boolean", "overloadedBoolean", "number", "spaceSeparated", "commaSeparated", "commaOrSpaceSeparated"] as const;
const flagName: Record<(typeof flags)[number], string> = {
  boolean: "BOOLEAN", overloadedBoolean: "OVERLOADED_BOOLEAN", number: "NUMBER",
  spaceSeparated: "SPACE_SEPARATED", commaSeparated: "COMMA_SEPARATED", commaOrSpaceSeparated: "COMMA_OR_SPACE_SEPARATED",
};
const names = new Set<string>(Object.keys(schema.required?.input ?? {}));
for (const defs of Object.values(schema.attributes ?? {})) for (const def of defs as (string | unknown[])[]) names.add(typeof def === "string" ? def : String(def[0]));
names.add("className").add("id");
type Found = Record<string, unknown> & { property: string; attribute: string };
const property = (name: string, info: Found) => {
  const set = flags.filter((flag) => info[flag]).map((flag) => `HtmlProperty.${flagName[flag]}`);
  return `        ${str(name)} to HtmlProperty(${str(name)}, ${str(info.attribute)}, ${set.length ? set.join(" or ") : "0"}),`;
};
const spellings: string[] = [];
const props: string[] = [];
// SVG elements are named and typed by the SVG schema (hastscript's `s`), where a name it does
// not define (`abbr`) is kept as written and untyped, and `for` is no `htmlFor`.
const svgSpellings: string[] = [];
const svgProps: string[] = [];
for (const name of [...names].sort()) {
  const info = find(html, name) as unknown as Found;
  if (info.property !== name) throw new Error(`${name} resolves to ${info.property}`);
  props.push(property(name, info));
  for (const spelling of new Set([info.attribute.toLowerCase(), name.toLowerCase()])) {
    if (find(html, spelling).property === name) spellings.push(`        ${str(spelling)} to ${str(name)},`);
  }
  const svgInfo = find(svg, name) as unknown as Found;
  let reachable = false;
  for (const spelling of new Set([svgInfo.attribute.toLowerCase(), name.toLowerCase()])) {
    if (find(svg, spelling).property === name) {
      svgSpellings.push(`        ${str(spelling)} to ${str(name)},`);
      reachable = true;
    }
  }
  if (reachable) svgProps.push(property(name, svgInfo));
}

const kotlin = `// GENERATED by \`bun android/scripts/gen-html-schema.ts\` from markdownSanitizeSchema and property-information — do not edit.
package com.hienlh.ppm.chat

/** The web's \`markdownSanitizeSchema\`: what rehype-sanitize keeps of HTML inside markdown. */
internal object HtmlSchema {
    /** Elements kept; any other is unwrapped (its children stay) unless [strip] drops it whole. */
    val tagNames: Set<String> = setOf(${list(schema.tagNames ?? [])})

    /** Elements dropped with everything inside them. */
    val strip: Set<String> = setOf(${list(schema.strip ?? [])})

    /** Elements kept only inside one of these. */
    val ancestors: Map<String, List<String>> = mapOf(
${Object.entries(schema.ancestors ?? {}).map(([tag, within]) => `        ${str(tag)} to listOf(${list(within as string[])}),`).join("\n")}
    )

    /** Properties kept per element, then on any element (\`*\`). */
    val attributes: Map<String, List<HtmlAllowed>> = mapOf(
${attributes.join("\n")}
    )

    /** Properties an element always ends up with, after its own. */
    val required: Map<String, List<Pair<String, HtmlValue>>> = mapOf(
${required.join("\n")}
    )

    /** Properties whose values get [CLOBBER_PREFIX], so they cannot name globals. */
    val clobber: Set<String> = setOf(${list(schema.clobber ?? [])})
    const val CLOBBER_PREFIX = ${str(schema.clobberPrefix ?? "")}

    /** Properties whose URL may only use these schemes (a value with no scheme passes). */
    val protocols: Map<String, List<String>> = mapOf(
${Object.entries(schema.protocols ?? {}).map(([key, schemes]) => `        ${str(key)} to listOf(${list(schemes as string[])}),`).join("\n")}
    )

    /** hast's property for each attribute spelling (lower case, as the parser hands it over) that can reach one the schema keeps. */
    val propertyOf: Map<String, String> = mapOf(
${spellings.join("\n")}
    )

    /** How hastscript reads, and hast-util-to-html writes, each of those properties. */
    val properties: Map<String, HtmlProperty> = mapOf(
${props.join("\n")}
    )

    /** [propertyOf] for SVG elements. */
    val svgPropertyOf: Map<String, String> = mapOf(
${svgSpellings.join("\n")}
    )

    /** [properties] for SVG elements. */
    val svgProperties: Map<String, HtmlProperty> = mapOf(
${svgProps.join("\n")}
    )
}
`;
writeFileSync(out, kotlin);
console.log(`${schema.tagNames?.length} tags, ${props.length} properties, ${spellings.length} spellings, ${svgSpellings.length} SVG spellings -> ${out}`);
